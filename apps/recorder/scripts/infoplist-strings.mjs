#!/usr/bin/env node
/* global console, process, URL */
// macOS shows the permission explanations from Info.plist, translated by
// `<lang>.lproj/InfoPlist.strings` in the bundle. This writes those files from
// the locale files (`macos.*` keys), so the text lives in one place.
//
//   node apps/recorder/scripts/infoplist-strings.mjs           write
//   node apps/recorder/scripts/infoplist-strings.mjs --check   fail if stale
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('..', import.meta.url);
const KEYS = { NSMicrophoneUsageDescription: 'macos.microphoneUsage', NSAudioCaptureUsageDescription: 'macos.audioCaptureUsage' };

export function render(lang) {
  const messages = JSON.parse(readFileSync(new URL(`locales/${lang}.json`, root), 'utf8'));
  const quote = (s) => s.replaceAll('\\', '\\\\').replaceAll('"', '\\"');
  const lines = Object.entries(KEYS).map(([plist, key]) => `"${plist}" = "${quote(messages[key])}";`);
  return `/* Generated by scripts/infoplist-strings.mjs from locales/${lang}.json. */\n${lines.join('\n')}\n`;
}

export function target(lang) {
  return fileURLToPath(new URL(`src-tauri/locales/${lang}.lproj/InfoPlist.strings`, root));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  let stale = false;
  for (const lang of ['en', 'da']) {
    const want = render(lang);
    const path = target(lang);
    const have = existsSync(path) ? readFileSync(path, 'utf8') : '';
    if (have === want) continue;
    if (process.argv.includes('--check')) {
      console.error(`${path} is stale; run scripts/infoplist-strings.mjs`);
      stale = true;
    } else {
      mkdirSync(new URL(`src-tauri/locales/${lang}.lproj/`, root), { recursive: true });
      writeFileSync(path, want);
      console.log(`wrote ${path}`);
    }
  }
  process.exit(stale ? 1 : 0);
}
